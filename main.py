"""
Frontend Tech Radar & Web Ecosystem Pulse Generator
Zero external dependencies (uses standard library urllib, json, datetime).
"""

import os
import json
import datetime
import urllib.request
import urllib.error

USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) FrontendRadarBot/1.0"

def fetch_json(url, headers=None):
    if headers is None:
        headers = {}
    headers["User-Agent"] = USER_AGENT
    
    github_token = os.environ.get("GITHUB_TOKEN")
    if "api.github.com" in url and github_token:
        headers["Authorization"] = f"Bearer {github_token}"
        
    req = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except Exception as e:
        print(f"[-] Warning: Failed to fetch {url}: {e}")
        return None

def get_trending_frontend_repos():
    """Fetch top active frontend & UI repositories."""
    seven_days_ago = (datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(days=7)).strftime("%Y-%m-%d")
    
    queries = [
        ("TypeScript & Core", f"language:typescript+created:>{seven_days_ago}+stars:>15"),
        ("React & Next.js", f"topic:react+stars:>20+pushed:>{seven_days_ago}"),
        ("UI, Design Systems & CSS", f"topic:ui+topic:design-system+stars:>15"),
        ("Tooling & Web Performance", f"topic:bundler+topic:devtools+stars:>10")
    ]
    
    results = {}
    for category, q in queries:
        url = f"https://api.github.com/search/repositories?q={q}&sort=stars&order=desc&per_page=3"
        data = fetch_json(url)
        if data and "items" in data:
            results[category] = [
                {
                    "name": item["full_name"],
                    "url": item["html_url"],
                    "stars": item["stargazers_count"],
                    "description": item["description"] or "No description provided."
                }
                for item in data["items"][:3]
            ]
        else:
            results[category] = []
    return results

def get_top_web_discussions():
    """Fetch top web and dev discussions from Hacker News."""
    top_ids_url = "https://hacker-news.firebaseio.com/v0/topstories.json"
    ids = fetch_json(top_ids_url)
    if not ids:
        return []
    
    keywords = ["web", "css", "js", "javascript", "typescript", "react", "ui", "design", "frontend", "browser", "performance"]
    stories = []
    
    for item_id in ids[:30]:
        item_url = f"https://hacker-news.firebaseio.com/v0/item/{item_id}.json"
        story = fetch_json(item_url)
        if story and "title" in story and "url" in story:
            title_lower = story["title"].lower()
            if any(k in title_lower for k in keywords) or len(stories) < 2:
                stories.append({
                    "title": story["title"],
                    "url": story.get("url", f"https://news.ycombinator.com/item?id={item_id}"),
                    "score": story.get("score", 0),
                    "comments": story.get("descendants", 0)
                })
        if len(stories) >= 5:
            break
            
    # Fallback if specific keywords are quiet today
    if len(stories) < 3 and ids:
        for item_id in ids[:5]:
            item_url = f"https://hacker-news.firebaseio.com/v0/item/{item_id}.json"
            story = fetch_json(item_url)
            if story and "title" in story:
                stories.append({
                    "title": story["title"],
                    "url": story.get("url", f"https://news.ycombinator.com/item?id={item_id}"),
                    "score": story.get("score", 0),
                    "comments": story.get("descendants", 0)
                })
            if len(stories) >= 5:
                break
                
    return stories[:5]

def generate_markdown(date_str, repos_by_cat, stories):
    lines = []
    lines.append(f"# 🎨 Frontend Tech Radar // {date_str}\n")
    lines.append(f"> Automated web telemetry and curated UI tooling. Generated by `devodrag/frontend-radar`.\n")
    lines.append("## ⚡ Trending Frontend & UI Repositories\n")
    
    for cat, repos in repos_by_cat.items():
        lines.append(f"### `{cat}`\n")
        if not repos:
            lines.append("_No new high-growth repos detected today._\n")
            continue
        for r in repos:
            lines.append(f"- **[{r['name']}]({r['url']})** (`★ {r['stars']}`)")
            lines.append(f"  _{r['description']}_\n")
            
    lines.append("## 📰 Web & Design Discussions\n")
    if stories:
        for s in stories:
            lines.append(f"- [{s['title']}]({s['url']}) — `▲ {s['score']} pts` | `💬 {s['comments']} comments`")
    else:
        lines.append("_Discussions feed unavailable today._")
        
    lines.append("\n---\n<sub>( • ) devodrag · Automated frontend telemetry</sub>\n")
    return "\n".join(lines)

def update_root_readme(date_str, repos_by_cat, stories):
    content = [
        '<div align="center">',
        '  <p><code><b>( • ) FRONTEND TECH RADAR &nbsp;|&nbsp; AUTOMATED DAILY PULSE</b></code></p>',
        f'  <h1><b>FRONTEND RADAR // {date_str}</b></h1>',
        '  <p>Curated telemetry on TypeScript, React, Next.js, Design Systems, and Web Performance.</p>',
        '</div>',
        '',
        '---',
        '',
        '### <code>( 01 ) // TRENDING UI & CLIENT TOOLS</code>',
        ''
    ]
    
    for cat, repos in repos_by_cat.items():
        content.append(f"#### **{cat.upper()}**")
        if not repos:
            content.append("_No new notable repos indexed._\n")
            continue
        for r in repos:
            content.append(f"- **[{r['name']}]({r['url']})** (`★ {r['stars']}`)")
            content.append(f"  _{r['description']}_\n")
            
    content.append('---')
    content.append('')
    content.append('### <code>( 02 ) // WEB & UI DISCUSSIONS</code>')
    content.append('')
    if stories:
        for s in stories:
            content.append(f"- [{s['title']}]({s['url']}) &nbsp; `▲ {s['score']} pts` &nbsp; `💬 {s['comments']}`")
    content.append('')
    content.append('---')
    content.append('')
    content.append('### <code>( 03 ) // ARCHIVE ACCESS</code>')
    content.append('')
    content.append(f"All historical daily digests are stored in [`archive/`](./archive/).")
    content.append('')
    content.append('<div align="center">')
    content.append('  <sub>Maintained automatically by <a href="https://github.com/devodrag">devodrag</a> via GitHub Actions</sub>')
    content.append('</div>')
    
    return "\n".join(content)

def main():
    today = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")
    print(f"[*] Running Frontend Radar for {today}...")
    
    os.makedirs("archive", exist_ok=True)
    
    repos = get_trending_frontend_repos()
    stories = get_top_web_discussions()
    
    # 1. Archive
    archive_path = os.path.join("archive", f"{today}.md")
    archive_md = generate_markdown(today, repos, stories)
    with open(archive_path, "w", encoding="utf-8") as f:
        f.write(archive_md)
    print(f"[+] Saved archive: {archive_path}")
    
    # 2. README.md
    readme_md = update_root_readme(today, repos, stories)
    with open("README.md", "w", encoding="utf-8") as f:
        f.write(readme_md)
    print(f"[+] Updated root README.md")

if __name__ == "__main__":
    main()
